// Machine-readable documentation (llmstxt.org): packages/llms.txt indexes the packages and the UI
// kit, and packages/components/<id>.md gives each component's specification, tokens, platform
// mapping and web example as Markdown. An agent or a reader without the reference page gets the
// same contract the kit tests hold, from the same sources (kit/components/, kit/web/examples.html).
import { WCAG, type Component } from "../kit.ts";
import type { Model } from "../model.ts";
import { cssName } from "./css.ts";

const HEADER = (source: string): string =>
  `<!-- GENERATED by nddev-design-system (\`just generate\`). Edit ${source}. -->\n`;

const PACKAGES: [dir: string, title: string, holds: string][] = [
  [
    "web",
    "Web",
    "tokens.css, kit.css, text-styles.css, tokens.json, icons.json, reference.html",
  ],
  [
    "apple",
    "Swift (iOS, iPadOS, macOS)",
    "a Swift package with tokens, text styles and fonts",
  ],
  [
    "kotlin",
    "Kotlin (Android, Compose)",
    "a Gradle module with tokens, text styles and fonts",
  ],
  ["flutter", "Flutter", "a Dart package with tokens, text styles and fonts"],
  ["rust", "Rust", "a crate with tokens and fonts"],
  [
    "fonts",
    "Fonts",
    "the font manifest (files, digests, preloads, fallback face) and TTF files",
  ],
  ["icons", "Icons", "the icon set as SVG and JSON"],
  ["brand", "Brand", "the mark and the direction icons, light and dark"],
  ["figma", "Figma", "the variables payload for the Figma library"],
];

const cell = (text: string): string =>
  text.replaceAll("|", "\\|").replaceAll("\n", " ");

/** The example as authored, without the indentation of its section in examples.html. */
function dedent(html: string): string {
  const [first = "", ...rest] = html.split("\n");
  const indent = Math.min(
    ...rest.filter((l) => l.trim()).map((l) => l.length - l.trimStart().length),
  );
  return [
    first,
    ...rest.map((l) => l.slice(Number.isFinite(indent) ? indent : 0)),
  ].join("\n");
}

function componentMarkdown(
  model: Model,
  c: Component,
  example: string | undefined,
): string {
  const lines: string[] = [
    HEADER(`kit/components/${c.id}.json`),
    `# ${c.name}`,
    "",
  ];
  lines.push(c.summary, "");
  lines.push(`- Status: ${c.status}`, `- Category: ${c.category}`);
  lines.push(
    `- Pattern: ${c.pattern.apg ? `WAI-ARIA APG “${c.pattern.apg}”; ` : ""}HTML \`${c.pattern.html}\``,
  );
  if (c.textStyle)
    lines.push(
      `- Text style: \`${c.textStyle}\` (\`.nd-text-${c.textStyle}\`)`,
    );
  lines.push("", "## Anatomy", "");
  for (const p of c.anatomy)
    lines.push(
      `- **${p.part}**${p.required ? "" : " (optional)"}: ${p.description}`,
    );
  lines.push("", "## Variants", "");
  for (const v of c.variants) lines.push(`- \`${v.id}\`: ${v.description}`);
  if (c.sizes.length)
    lines.push("", `Sizes: ${c.sizes.map((s) => `\`${s}\``).join(", ")}.`);
  lines.push("", "## States", "");
  for (const s of c.states)
    lines.push(`- \`${s}\`${c.cues[s] ? `: ${c.cues[s]}` : ""}`);
  if (c.keyboard.length) {
    lines.push("", "## Keyboard", "", "| Keys | Action |", "| --- | --- |");
    for (const k of c.keyboard)
      lines.push(`| ${cell(k.keys)} | ${cell(k.action)} |`);
  }
  lines.push("", "## Accessibility", "", `- Role: ${c.a11y.role}`);
  if (c.a11y.name) lines.push(`- Name: ${c.a11y.name}`);
  for (const n of c.a11y.notes) lines.push(`- ${n}`);
  lines.push("", "WCAG 2.2 success criteria:", "");
  for (const sc of c.a11y.wcag)
    lines.push(`- ${sc} ${WCAG[sc]?.title ?? ""} (${WCAG[sc]?.level ?? ""})`);
  if (c.contrast.length) {
    lines.push(
      "",
      "## Contrast",
      "",
      "Each pair meets its ratio in every theme and direction (checked on every build).",
      "",
      "| Foreground | Background | Minimum |",
      "| --- | --- | --- |",
    );
    for (const p of c.contrast)
      lines.push(`| \`${p.fg}\` | \`${p.bg}\` | ${String(p.min)}:1 |`);
  }
  if (c.tokens) {
    const group = c.tokens;
    const ids = model.ids.filter(
      (id) => model.owner.get(id) === "component" && id.split(".")[0] === group,
    );
    lines.push(
      "",
      "## Tokens",
      "",
      "| Token | CSS custom property |",
      "| --- | --- |",
    );
    for (const id of ids) lines.push(`| \`${id}\` | \`${cssName(id)}\` |`);
  }
  lines.push(
    "",
    "## Platforms",
    "",
    "| Platform | Implementation |",
    "| --- | --- |",
  );
  for (const [p, v] of Object.entries(c.platforms))
    lines.push(`| ${p} | ${cell(v)} |`);
  if (c.web) {
    const modifiers = c.web.modifiers.map((m) => `\`.${m}\``).join(", ");
    lines.push(
      "",
      `Web: \`.${c.web.class}\` in kit.css${modifiers ? `; modifiers ${modifiers}` : ""}.`,
    );
  }
  if (example)
    lines.push(
      "",
      "## Web example",
      "",
      "From the reference page:",
      "",
      "```html",
      dedent(example),
      "```",
    );
  lines.push("");
  return lines.map((line) => line.trimEnd()).join("\n");
}

export function emitLlms(
  model: Model,
  components: Component[],
  examples: Map<string, string>,
): Map<string, string> {
  const out = new Map<string, string>();
  const directions = model.registry.directions
    .map((d) => `\`${d.id}\``)
    .join(", ");
  const themes = model.themes.map((t) => `\`${t.id}\``).join(", ");
  const index: string[] = [
    "# OpenNetwork Design System",
    "",
    `> Design tokens, text styles, fonts, icons and a UI kit of ${String(components.length)} accessible components for OpenNetwork (${directions}) in the themes ${themes}, for the web, Apple platforms, Android, Flutter and Rust. Light is the default theme.`,
    "",
    "Products consume a release by copying a package directory from the tag `vX.Y.Z` and recording the tag and the directory digest; the copy is never edited. The generator verifies the declared WCAG 2.2 contrast pairs in every theme, and each component names its keyboard behaviour, accessibility contract and platform equivalents.",
    "",
    "## Packages",
    "",
    ...PACKAGES.map(
      ([dir, title, holds]) => `- [${title}](${dir}/README.md): ${holds}`,
    ),
    "",
    "## Components",
    "",
    ...components.map(
      (c) => `- [${c.name}](components/${c.id}.md): ${c.summary}`,
    ),
    "",
    "## Optional",
    "",
    "- [Token listing](web/tokens.json): the registry, breakpoints, text styles and every public token with its description and default value, and the value in every theme of each theme token",
    "- [Font manifest](fonts/manifest.json): font files with digests, unicode ranges, preloads and the fallback face",
    "- [Figma variables](figma/variables.json): the Figma library payload",
    "",
  ];
  out.set("llms.txt", index.join("\n"));
  for (const c of components)
    out.set(
      `components/${c.id}.md`,
      componentMarkdown(
        model,
        c,
        // The reference page fills the icon gallery from packages/icons at build time.
        examples
          .get(c.id)
          ?.replace(
            '<div class="nd-cluster" data-icons></div>',
            '<!-- Each icon of packages/icons: <svg class="nd-icon" viewBox="…" fill="none" aria-hidden="true" focusable="false">…</svg> -->',
          ),
      ),
    );
  return out;
}
