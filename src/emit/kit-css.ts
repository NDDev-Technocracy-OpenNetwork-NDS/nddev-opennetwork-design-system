// The kit's web stylesheets: kit/web/kit.css (authored: base and component rules over the tokens)
// and the text styles as classes, generated from kit/text-styles.json so the web, native packages
// and Figma share one definition. A script adjusts a style by language: Arabic and Chinese take
// their family, drop tracking and case, and running text takes their leading. The text styles
// also declare the fallback face their families name, so text set before the web font arrives
// takes the space Plex will take.
import { readFileSync } from "node:fs";
import { ROOT } from "../dtcg.ts";
import type { Fallback } from "../fonts.ts";
import { readTextStyles } from "../kit.ts";
import type { Model } from "../model.ts";
import { cssName } from "./css.ts";

const HEADER =
  "/* GENERATED by nddev-opennetwork-design-system (`just generate`) from kit/. Do not edit. */\n";

const percent = (ratio: number): string =>
  `${String(Math.round(ratio * 1e4) / 100)}%`;

/** A local face scaled to the web font's advance and vertical metrics (font-display swap moves little). */
export function fallbackFace(fallback: Fallback): string {
  return [
    "@font-face {",
    `  font-family: '${fallback.family}';`,
    `  src: ${fallback.local.map((name) => `local('${name}')`).join(", ")};`,
    `  size-adjust: ${percent(fallback.sizeAdjust)};`,
    `  ascent-override: ${percent(fallback.ascentOverride)};`,
    `  descent-override: ${percent(fallback.descentOverride)};`,
    `  line-gap-override: ${percent(fallback.lineGapOverride)};`,
    "}",
    "",
  ].join("\n");
}

export function emitTextStylesCss(
  model: Model,
  fallback: Fallback | null,
): string {
  const { styles, scripts } = readTextStyles(model);
  const v = (id: string): string => `var(${cssName(id)})`;
  const out: string[] = [
    HEADER,
    ...(fallback ? [fallbackFace(fallback)] : []),
    "@layer base {",
  ];
  for (const s of styles) {
    const size =
      s.scale === 1 ? v(s.size) : `calc(${v(s.size)} * ${String(s.scale)})`;
    out.push(
      `  .nd-text-${s.id} {`,
      `    font-family: ${v(s.family)};`,
      `    font-size: ${size};`,
      `    line-height: ${v(s.leading)};`,
      `    font-weight: ${v(s.weight)};`,
      `    letter-spacing: ${v(s.tracking)};`,
      ...(s.upper ? ["    text-transform: uppercase;"] : []),
      ...(s.wrap ? [`    text-wrap: ${s.wrap};`] : []),
      "  }",
    );
  }
  for (const sc of scripts) {
    const langs = sc.languages.map((l) => `:lang(${l})`).join(", ");
    const sans = styles
      .filter((s) => s.family === "font.sans")
      .map((s) => `.nd-text-${s.id}`);
    const rules: string[] = [];
    if (sc.family !== "font.sans")
      rules.push(
        `  :is(${sans.join(", ")}):where(${langs}) {`,
        `    font-family: ${v(sc.family)};`,
        "  }",
      );
    if (!sc.tracking || !sc.case)
      rules.push(
        `  [class*='nd-text-']:where(${langs}) {`,
        ...(sc.tracking ? [] : ["    letter-spacing: 0;"]),
        ...(sc.case ? [] : ["    text-transform: none;"]),
        "  }",
      );
    if (sc.bodyLeading)
      rules.push(
        `  :is(${styles
          .filter((s) => s.body)
          .map((s) => `.nd-text-${s.id}`)
          .join(", ")}):where(${langs}) {`,
        `    line-height: ${v(sc.bodyLeading)};`,
        "  }",
      );
    out.push(...rules);
  }
  out.push("}", "");
  return out.join("\n");
}

export function emitKitCss(): string {
  return `${HEADER}${readFileSync(`${ROOT}kit/web/kit.css`, "utf8")}`;
}
