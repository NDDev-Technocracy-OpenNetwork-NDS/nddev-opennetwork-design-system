// The web package's listing (packages/web/tokens.json): what TypeScript needs beside the CSS — the
// registry (themes with their schemes, directions, platforms), the brand seeds the icon generator
// draws with, breakpoints in px and rem for media queries (custom properties cannot be used there),
// the kit's text styles by custom property, and every public token with its property name, owner,
// description and value at the defaults; a theme's token whose value differs between themes also
// lists its value in every theme (a build that draws per theme, such as the frames' art, reads it).
import { TOKENS, isObject, readJson, type Json } from "../dtcg.ts";
import { readTextStyles } from "../kit.ts";
import { nd, type Model, type Token } from "../model.ts";
import { cssName, inCss, literal } from "./css.ts";

const hexOf = (v: Json | undefined): string => {
  if (!isObject(v) || typeof v["$value"] !== "object")
    throw new Error("brand: not a colour token");
  const value = v["$value"];
  if (!isObject(value) || typeof value["hex"] !== "string")
    throw new Error("brand: no hex");
  return value["hex"].toUpperCase();
};

export function emitListing(model: Model): string {
  const r = model.registry;
  const at = model.get({});
  const perTheme = model.themes.map(
    (t) => [t.id, model.get({ theme: t.id })] as const,
  );
  const valueOf = (t: Token): string => {
    const css = nd(t)["css"];
    return typeof css === "string" ? css : literal(t);
  };
  const themeFile = (id: string): Record<string, Json> =>
    readJson(`${TOKENS}intent/themes/${id}.tokens.json`);
  const themes = model.themes.map((t) => {
    const ext = themeFile(t.id)["$extensions"];
    const own = isObject(ext) ? ext["ai.nddev"] : undefined;
    const meta = isObject(own) && isObject(own["theme"]) ? own["theme"] : {};
    return {
      id: t.id,
      scheme: t.scheme,
      ...(typeof meta["extends"] === "string"
        ? { extends: meta["extends"] }
        : {}),
      ...(t.source ? { source: t.source } : {}),
    };
  });
  const brandFile = readJson(`${TOKENS}intent/brand.tokens.json`);
  const seeds = brandFile["brand"];
  const backgrounds = brandFile["brand-icon-background"];
  if (!isObject(seeds) || !isObject(backgrounds))
    throw new Error("brand intent");

  const breakpoints = Object.fromEntries(
    model.ids
      .filter((id) => id.startsWith("breakpoint."))
      .map((id) => {
        const v = at[id]?.$value;
        if (!isObject(v) || typeof v["value"] !== "number") throw new Error(id);
        const pxValue = v["unit"] === "rem" ? v["value"] * 16 : v["value"];
        return [
          id.slice("breakpoint.".length),
          { px: pxValue, rem: pxValue / 16 },
        ];
      }),
  );

  const kit = readTextStyles(model);
  const listing = {
    $description:
      "The NDDev design system for TypeScript: registry, brand seeds, breakpoints, text styles and every public token. Generated by nddev-design-system; tokens.css carries the values.",
    registry: {
      directions: r.directions,
      themes,
      defaultTheme: r.themes.default,
      defaultChoice: r.themes.defaultChoice ?? r.themes.default,
      systemThemes: r.themes.system,
      ...(r.themes.contrast ? { contrastThemes: r.themes.contrast } : {}),
      platforms: model.modifier("platform").contexts,
      cssPlatforms: r.platforms?.css ?? ["web"],
      defaultPlatform: model.modifier("platform").default,
      densities: model.modifier("density").contexts,
      defaultDensity: model.modifier("density").default,
      motions: model.modifier("motion").contexts,
      defaultMotion: model.modifier("motion").default,
    },
    brand: {
      seeds: Object.fromEntries(
        r.directions.map((d) => [d.id, hexOf(seeds[d.id])]),
      ),
      iconBackgrounds: Object.fromEntries(
        Object.entries(backgrounds)
          .filter(([k]) => !k.startsWith("$"))
          .map(([k, v]) => [k, hexOf(v)]),
      ),
    },
    breakpoints,
    textStyles: kit.styles.map((s) => ({
      role: s.id,
      description: s.description,
      family: cssName(s.family),
      size: cssName(s.size),
      leading: cssName(s.leading),
      weight: cssName(s.weight),
      tracking: cssName(s.tracking),
      uppercase: s.upper,
      body: s.body,
      scale: s.scale,
    })),
    scripts: kit.scripts.map((s) => ({
      script: s.id,
      family: cssName(s.family),
      tracking: s.tracking,
      case: s.case,
      ...(s.bodyLeading ? { bodyLeading: cssName(s.bodyLeading) } : {}),
    })),
    tokens: model.ids.map((id) => {
      const t = at[id];
      if (!t) throw new Error(`listing: ${id}`);
      const owner = model.owner.get(id) ?? "foundation";
      const value = valueOf(t);
      const themes =
        owner === "theme"
          ? Object.fromEntries(
              perTheme.map(([theme, set]) => {
                const own = set[id];
                if (!own) throw new Error(`listing: ${id} in ${theme}`);
                return [theme, valueOf(own)];
              }),
            )
          : {};
      return {
        id,
        type: t.$type,
        owner,
        ...(inCss(id) ? { css: cssName(id) } : {}),
        value,
        ...(Object.values(themes).some((v) => v !== value) ? { themes } : {}),
        ...(t.$description ? { description: t.$description } : {}),
        ...(t.$deprecated !== undefined ? { deprecated: t.$deprecated } : {}),
      };
    }),
  };
  return `${JSON.stringify(listing, null, 2)}\n`;
}
