// The domain producer validates a complete candidate before publication. generate derives and
// builds from one in-memory model; derive/build retain their explicit partial-phase contracts.
import { readFileSync, readdirSync, lstatSync } from "node:fs";
import { relative } from "node:path";
import { ROOT, TOKENS, stableJson } from "./dtcg.ts";
import { derive } from "./derive.ts";
import { build } from "./build.ts";
import { loadModel } from "./model.ts";
import {
  sha256,
  withGeneration,
  type Content,
  type InputHashes,
  type Scope,
} from "./generated-output.ts";

type Files = Map<string, Content>;
function relativeFiles(files: ReadonlyMap<string, Content>): Files {
  return new Map(
    [...files].map(([path, data]) => [
      relative(ROOT, path).split("\\").join("/"),
      data,
    ]),
  );
}
function derivedFiles() {
  const d = derive();
  const files: Files = new Map();
  for (const [path, json] of d.files)
    files.set("tokens/" + path, stableJson(json));
  files.set(
    "tokens/derived/contrast.json",
    stableJson({ pairs: d.checks.length, checks: d.checks } as never),
  );
  return { files, sources: d.files, checks: d.checks.length };
}

// Producer inputs, not installed environments or private Git metadata. Fontsource bytes and
// licences are separately validated by readFonts before an emitter returns a candidate.
function sourceInputs(): InputHashes {
  const hashes: InputHashes = {};
  const walk = (name: string): void => {
    const path = ROOT + name;
    const stat = lstatSync(path);
    if (stat.isSymbolicLink())
      throw new Error(
        "Authored source link is not a generation input: " + name,
      );
    if (stat.isDirectory()) {
      for (const entry of readdirSync(path).sort()) walk(name + "/" + entry);
    } else if (stat.isFile()) hashes[name] = sha256(readFileSync(path));
    else throw new Error("Unsupported producer input: " + name);
  };
  for (const name of [
    "src",
    "kit",
    "icons",
    "brand",
    "fonts",
    "adapters",
    "tests/flutter",
    "licenses",
    "vendor",
    "LICENSE",
    "NOTICE",
    "THIRD_PARTY_NOTICES.md",
    ".gitattributes",
    "package.json",
    "bun.lock",
  ])
    walk(name);
  for (const name of readdirSync(TOKENS).sort())
    if (!["derived", "nddev.resolver.json", "tokens.json"].includes(name))
      walk("tokens/" + name);
  return Object.fromEntries(Object.entries(hashes).sort());
}
function packageInputs(
  authored: InputHashes,
  files: Files,
  fromDisk = false,
): InputHashes {
  const inputs = { ...authored };
  for (const [name, body] of files)
    inputs[name] = sha256(fromDisk ? readFileSync(ROOT + name) : body);
  return Object.fromEntries(Object.entries(inputs).sort());
}

const command = process.argv[2];
if (!["derive", "build", "generate", "check"].includes(command ?? "")) {
  console.error("usage: node src/cli.ts derive|build|generate|check");
  process.exit(2);
}
await withGeneration(ROOT, command !== "check", async (session) => {
  const before = sourceInputs();
  const derived = derivedFiles();
  const fresh = relativeFiles(await build(await loadModel(derived.sources)));
  const all = new Map([...derived.files, ...fresh]);
  const inputs: Partial<Record<Scope, InputHashes>> = {
    derived: before,
    packages: packageInputs(before, derived.files),
  };
  if (JSON.stringify(sourceInputs()) !== JSON.stringify(before))
    throw new Error(
      "Authored inputs changed during generation; no outputs published",
    );
  if (command === "check") {
    session.check(all, inputs);
    console.log(
      "check: " +
        String(derived.checks) +
        " contrast pairs pass; generated bytes and ownership are current",
    );
    return;
  }
  if (command === "generate") {
    session.publish(all, inputs, ["derived", "packages"], new Set(all.keys()));
    console.log(
      "generate: " +
        String(all.size) +
        " outputs; " +
        String(derived.checks) +
        " contrast pairs pass",
    );
  } else if (command === "derive") {
    session.publish(
      derived.files,
      { derived: before },
      ["derived"],
      new Set(all.keys()),
    );
    console.log(
      "derive: " +
        String(derived.files.size) +
        " outputs; packages remain a separate phase",
    );
  } else {
    const fromDisk = relativeFiles(await build());
    if (JSON.stringify(sourceInputs()) !== JSON.stringify(before))
      throw new Error(
        "Authored inputs changed during build; no outputs published",
      );
    session.publish(
      fromDisk,
      { packages: packageInputs(before, derived.files, true) },
      ["packages"],
      new Set(all.keys()),
    );
    console.log(
      "build: " +
        String(fromDisk.size) +
        " outputs; derived tokens remain a separate phase",
    );
  }
});
